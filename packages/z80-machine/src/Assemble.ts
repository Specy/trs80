import {Asm, FileInfo, FileSystem, SourceFile} from "z80-asm";
import {KnownLabel} from "z80-base";
import {DEFAULT_ENTRY_PATHNAME, MAX_INCLUDE_DEPTH} from "./Constants.js";
import {directoryOfPathname, normalizePathname} from "./Paths.js";

/**
 * Prefix of the assembler's message for an include whose file it could not
 * load. We refuse to load some includes on purpose, and say why instead.
 */
const CANNOT_READ_PREFIX = "cannot read file ";

// Codecs for InMemoryFileSystem, which stores a file either way round.
const TEXT_ENCODER = new TextEncoder();
const TEXT_DECODER = new TextDecoder();

/**
 * A problem found while assembling, tied to a source line.
 */
export interface AssemblyDiagnostic {
    pathname: string;

    /**
     * Zero-based line number within the file, or undefined for lines
     * generated by macro or include expansion.
     */
    lineNumber: number | undefined;

    message: string;
}

/**
 * Options for {@link assemble} and {@link check}.
 */
export interface AssembleOptions {
    /**
     * Which file to assemble when sources is a map of several files.
     * Defaults to "main.asm" if present, or the map's only file.
     */
    entryPathname?: string;

    /**
     * Predefined labels to make available to the source.
     */
    knownLabels?: KnownLabel[];
}

/**
 * A read-only in-memory {@link FileSystem} over a map of pathname to file
 * contents, so the assembler's include and incbin directives work without
 * a real filesystem.
 *
 * A file's contents are either a string (source text) or a Uint8Array (raw
 * bytes, for data that "#insert" embeds). Give binary data as a Uint8Array:
 * a string read as binary is encoded as UTF-8, which cannot represent an
 * arbitrary byte (a sprite or font table would come back longer than it
 * went in). A Uint8Array read as text is decoded as UTF-8.
 */
export class InMemoryFileSystem implements FileSystem {
    // Map from normalized pathname to contents of the file.
    private readonly files = new Map<string, string | Uint8Array>();

    constructor(files: Record<string, string | Uint8Array>) {
        for (const pathname of Object.keys(files)) {
            this.files.set(normalizePathname(pathname), files[pathname]);
        }
    }

    readTextFile(pathname: string): string[] | undefined {
        const contents = this.files.get(normalizePathname(pathname));
        if (contents === undefined) {
            return undefined;
        }

        const text = typeof contents === "string" ? contents : TEXT_DECODER.decode(contents);

        // Split on either kind of line ending, and don't leave the \r behind.
        return text.split(/\r\n|\r|\n/);
    }

    readBinaryFile(pathname: string): Uint8Array | undefined {
        const contents = this.files.get(normalizePathname(pathname));
        if (contents === undefined) {
            return undefined;
        }

        // Bytes are handed back exactly as they were given.
        return typeof contents === "string" ? TEXT_ENCODER.encode(contents) : contents;
    }

    readDirectory(pathname: string): string[] | undefined {
        const dir = normalizePathname(pathname);

        // Files directly in this directory, by basename.
        const filenames: string[] = [];
        for (const filePathname of this.files.keys()) {
            if (directoryOfPathname(filePathname) === dir) {
                filenames.push(filePathname.substring(dir === "" ? 0 : dir.length + 1));
            }
        }

        // There are no empty directories in a flat map of files, so a directory
        // with nothing in it doesn't exist as far as we're concerned.
        return filenames.length === 0 ? undefined : filenames.sort();
    }
}

/**
 * The assembler, with a guard against includes that never end. The
 * assembler expands an "#include" by splicing the included file's lines
 * into the listing it is walking, and does not check whether the file is
 * already being included, so a cycle expands forever in a synchronous
 * loop: the thread never returns, and memory grows until it runs out. The
 * source we are handed is arbitrary text, and may well be half-written, so
 * the guard belongs here.
 */
class GuardedAsm extends Asm {
    // Pathnames we refused to load, and why, keyed the way the assembler
    // asked for them so that we can recognize its own error message.
    private readonly refusedIncludes = new Map<string, string>();

    public loadSourceFile(pathname: string, parentFileInfo: FileInfo | undefined): SourceFile | undefined {
        // The top-level file is not an include and can't be a cycle.
        if (parentFileInfo !== undefined) {
            // Compare normalized pathnames: the entry file keeps the spelling
            // the caller used ("main.asm") while an include of it resolves to
            // "./main.asm", and those are the same file.
            const normalized = normalizePathname(pathname);

            for (let fileInfo: FileInfo | undefined = parentFileInfo;
                 fileInfo !== undefined;
                 fileInfo = fileInfo.parentFileInfo) {

                if (normalizePathname(fileInfo.pathname) === normalized) {
                    this.refusedIncludes.set(pathname, "include cycle: " + normalized);
                    return undefined;
                }
            }

            if (parentFileInfo.depth >= MAX_INCLUDE_DEPTH) {
                this.refusedIncludes.set(pathname, "includes nested more than " +
                    MAX_INCLUDE_DEPTH + " deep");
                return undefined;
            }
        }

        return super.loadSourceFile(pathname, parentFileInfo);
    }

    /**
     * Why we refused this include, if the assembler's message is about a
     * file we refused on purpose. Otherwise the assembler's own message,
     * which really is about a file it could not read.
     */
    public explainError(error: string): string {
        if (error.startsWith(CANNOT_READ_PREFIX)) {
            const reason = this.refusedIncludes.get(error.substring(CANNOT_READ_PREFIX.length));
            if (reason !== undefined) {
                return reason;
            }
        }

        return error;
    }
}

/**
 * A contiguous run of assembled bytes.
 */
export interface AssemblySegment {
    address: number;
    bytes: Uint8Array;
}

/**
 * Everything produced by one assembly: the diagnostics, the entry point,
 * the binary, and the full assembler object (symbols, per-line listing
 * with addresses and bytes, file structure) for tooling to dig into.
 */
export class AssemblyResult {
    /**
     * The underlying assembler, exposing the complete listing
     * (assembledLines with address, binary, and per-line errors), the
     * symbol table with definitions and references, and the file tree.
     */
    public readonly asm: Asm;

    /**
     * The assembled entry file, or undefined if it could not be read.
     */
    public readonly sourceFile: SourceFile | undefined;

    public readonly diagnostics: AssemblyDiagnostic[];

    /**
     * Where execution should start: the END directive's address if the
     * source has one, otherwise the lowest address that received code.
     * Zero for an empty program.
     */
    public readonly entryPoint: number;

    constructor(asm: Asm, sourceFile: SourceFile | undefined,
                diagnostics: AssemblyDiagnostic[], entryPoint: number) {

        this.asm = asm;
        this.sourceFile = sourceFile;
        this.diagnostics = diagnostics;
        this.entryPoint = entryPoint;
    }

    /**
     * Whether the assembly failed. A result with errors cannot be loaded
     * into a machine.
     */
    public hasErrors(): boolean {
        return this.diagnostics.length > 0;
    }

    /**
     * The assembled bytes as contiguous segments, in address order.
     */
    public segments(): AssemblySegment[] {
        // Lines that generated bytes, in memory order.
        const lines = this.asm.assembledLines
            .filter(line => line.binary.length > 0)
            .sort((a, b) => a.address - b.address);

        const segments: AssemblySegment[] = [];
        let address = 0;
        let bytes: number[] = [];

        const flush = () => {
            if (bytes.length > 0) {
                segments.push({ address: address, bytes: Uint8Array.from(bytes) });
                bytes = [];
            }
        };

        for (const line of lines) {
            // Start a new segment unless this line continues the one we're building.
            if (bytes.length === 0 || line.address !== address + bytes.length) {
                flush();
                address = line.address;
            }
            for (const byte of line.binary) {
                bytes.push(byte);
            }
        }
        flush();

        return segments;
    }
}

/**
 * Figure out which file of the map to assemble. Throws if we can't tell,
 * which is a programmer error.
 */
function resolveEntryPathname(files: Record<string, string | Uint8Array>,
                              entryPathname: string | undefined): string {

    if (entryPathname !== undefined) {
        return entryPathname;
    }

    const pathnames = Object.keys(files);

    if (pathnames.indexOf(DEFAULT_ENTRY_PATHNAME) >= 0) {
        return DEFAULT_ENTRY_PATHNAME;
    }

    if (pathnames.length === 1) {
        return pathnames[0];
    }

    if (pathnames.length === 0) {
        throw new Error("no source files were provided to assemble");
    }

    throw new Error("must specify entryPathname: there's no \"" + DEFAULT_ENTRY_PATHNAME +
        "\" among the source files (" + pathnames.join(", ") + ")");
}

/**
 * Assemble Z80 source code. Sources can be a single string, or a map of
 * pathname to contents when the program has several files (see
 * {@link AssembleOptions.entryPathname}). A file in the map can be a
 * Uint8Array of raw bytes, for data embedded with "#insert"; see
 * {@link InMemoryFileSystem}.
 */
export function assemble(sources: string | Record<string, string | Uint8Array>,
                         options?: AssembleOptions): AssemblyResult {

    const files = typeof sources === "string" ? { [DEFAULT_ENTRY_PATHNAME]: sources } : sources;
    const entryPathname = resolveEntryPathname(files, options?.entryPathname);

    const asm = new GuardedAsm(new InMemoryFileSystem(files));
    if (options?.knownLabels !== undefined) {
        asm.addKnownLabels(options.knownLabels);
    }
    const sourceFile = asm.assembleFile(entryPathname);

    // Gather the errors of every line of the listing, including included files
    // and expanded macros.
    const diagnostics: AssemblyDiagnostic[] = [];
    if (sourceFile === undefined) {
        diagnostics.push({
            pathname: normalizePathname(entryPathname),
            lineNumber: undefined,
            message: "cannot read file " + entryPathname,
        });
    } else {
        for (const line of asm.assembledLines) {
            if (line.error !== undefined) {
                diagnostics.push({
                    pathname: normalizePathname(line.fileInfo.pathname),
                    lineNumber: line.lineNumber,
                    message: asm.explainError(line.error),
                });
            }
        }
    }

    // The "end" directive wins, otherwise start at the lowest address that
    // received code. Data below the code (a message table at a low org, say)
    // must not become the entry point: the machine would execute the data.
    let entryPoint = asm.entryPoint;
    if (entryPoint === undefined) {
        let lowestCodeAddress: number | undefined = undefined;
        let lowestByteAddress: number | undefined = undefined;

        for (const line of asm.assembledLines) {
            if (line.binary.length === 0) {
                continue;
            }
            if (lowestByteAddress === undefined || line.address < lowestByteAddress) {
                lowestByteAddress = line.address;
            }
            if (!line.isData() && (lowestCodeAddress === undefined || line.address < lowestCodeAddress)) {
                lowestCodeAddress = line.address;
            }
        }

        // A program made entirely of data has nowhere better to start.
        entryPoint = lowestCodeAddress ?? lowestByteAddress;
    }

    return new AssemblyResult(asm, sourceFile, diagnostics, entryPoint ?? 0);
}

/**
 * Check Z80 source code without keeping the result: assemble and return
 * just the diagnostics. Suitable for editor squiggles.
 */
export function check(sources: string | Record<string, string | Uint8Array>,
                      options?: AssembleOptions): AssemblyDiagnostic[] {

    return assemble(sources, options).diagnostics;
}
