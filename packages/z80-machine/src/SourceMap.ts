import {SymbolInfo, SymbolType} from "z80-asm";
import {AssemblyResult} from "./Assemble.js";
import {CallStackFrame} from "./CallStack.js";
import {DEFAULT_ENTRY_PATHNAME, MEMORY_SIZE} from "./Constants.js";
import {normalizePathname} from "./Paths.js";
import type {Z80Machine} from "./Z80Machine.js";

/**
 * Key into the line-to-address map.
 */
function locationKey(pathname: string, lineNumber: number): string {
    return normalizePathname(pathname) + ":" + lineNumber;
}

/**
 * A place in the source code.
 */
export interface SourceLocation {
    pathname: string;

    /**
     * Zero-based line number within the file.
     */
    lineNumber: number;
}

/**
 * A call-stack frame annotated with the name of the routine being
 * executed, when the assembly has a label for it.
 */
export interface NamedCallStackFrame extends CallStackFrame {
    /**
     * The routine's label as it is spelled in the source, for display in a
     * debugger, or undefined if no symbol names the call target. The
     * assembler's identifiers are case-insensitive, so this is the
     * original spelling rather than the lower-cased canonical name that
     * {@link SourceMap.symbolAt} returns in
     * {@link SymbolInfo.name}.
     */
    name: string | undefined;
}

/**
 * Maps between memory addresses and source locations for one assembly,
 * and names things: which line generated an address (for showing the
 * current line), which address a line starts at (for breakpoints by
 * line), and which symbol an address belongs to (for naming call-stack
 * frames). The machine itself stays symbol-agnostic; this helper is the
 * join between it and an {@link AssemblyResult}.
 */
export class SourceMap {
    public readonly result: AssemblyResult;

    // Pathname of the file that was assembled, used as the default for
    // locationToAddress().
    private readonly entryPathname: string;

    // Source location of each address of the 64 kB address space, or undefined
    // if no line generated that byte.
    private readonly locationByAddress: (SourceLocation | undefined)[];

    // Map from locationKey() to the address of the first line there that
    // generated bytes.
    private readonly addressByLocation = new Map<string, number>();

    // Symbols that name a memory location, sorted by value, for symbolAt().
    private readonly addressSymbols: SymbolInfo[];

    constructor(result: AssemblyResult) {
        this.result = result;

        this.entryPathname = normalizePathname(
            result.sourceFile?.fileInfo.pathname ?? DEFAULT_ENTRY_PATHNAME);

        this.locationByAddress = new Array<SourceLocation | undefined>(MEMORY_SIZE);

        for (const line of result.asm.assembledLines) {
            // Lines that generated no bytes have no address of their own, and
            // lines expanded from macros or includes don't exist in any file.
            if (line.binary.length === 0 || line.lineNumber === undefined) {
                continue;
            }

            const location: SourceLocation = {
                pathname: normalizePathname(line.fileInfo.pathname),
                lineNumber: line.lineNumber,
            };

            for (let i = 0; i < line.binary.length; i++) {
                this.locationByAddress[(line.address + i) & 0xFFFF] = location;
            }

            // First line at a location wins, in case a file is included twice.
            const key = locationKey(location.pathname, location.lineNumber);
            if (!this.addressByLocation.has(key)) {
                this.addressByLocation.set(key, line.address);
            }
        }

        // Symbols we're willing to name an address after. We skip symbols that
        // were only referenced and never defined (they're errors anyway), and
        // constants, which the assembler marks as CONSTANT precisely because
        // they don't refer to a memory location. Everything else (CODE, BYTE,
        // WORD, ARRAY, and the UNKNOWN of known labels supplied for ROM
        // routines) labels an address, so it can own the addresses above it.
        this.addressSymbols = result.asm.symbols
            .filter(symbol => symbol.definitions.length > 0 && symbol.type !== SymbolType.CONSTANT)
            .sort((a, b) => a.value - b.value);
    }

    /**
     * The source line that generated the byte at the given address, or
     * undefined if no line did.
     */
    public addressToLocation(address: number): SourceLocation | undefined {
        if (address < 0 || address >= MEMORY_SIZE) {
            return undefined;
        }

        return this.locationByAddress[address];
    }

    /**
     * The address of the first byte generated by the given line, or
     * undefined if the line generated none. The pathname defaults to the
     * assembly's entry file.
     */
    public locationToAddress(lineNumber: number, pathname?: string): number | undefined {
        return this.addressByLocation.get(locationKey(pathname ?? this.entryPathname, lineNumber));
    }

    /**
     * The symbol whose value is nearest at or below the given address,
     * or undefined if there is none. This is the label the address
     * "belongs to".
     */
    public symbolAt(address: number): SymbolInfo | undefined {
        // Binary search for the last symbol at or below the address.
        let symbol: SymbolInfo | undefined = undefined;
        let low = 0;
        let high = this.addressSymbols.length - 1;

        while (low <= high) {
            const mid = (low + high) >> 1;
            if (this.addressSymbols[mid].value <= address) {
                symbol = this.addressSymbols[mid];
                low = mid + 1;
            } else {
                high = mid - 1;
            }
        }

        return symbol;
    }

    /**
     * The machine's call stack with each frame named after the symbol at
     * its call target, as the label is spelled in the source. See
     * {@link Z80Machine.getCallStack}.
     */
    public namedCallStack(machine: Z80Machine): NamedCallStackFrame[] {
        return machine.getCallStack().map(frame => ({
            ...frame,
            name: this.symbolAt(frame.targetAddress)?.originalSpelling,
        }));
    }
}
